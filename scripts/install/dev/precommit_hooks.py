def linux_seal_constants():
    """Use Linux UAPI values even when the Python build omitted their bindings."""
    if not sys.platform.startswith("linux"):
        raise SetupError("immutable executable seals require Linux")
    required = (
        getattr(fcntl, "F_SEAL_SEAL", 1) | getattr(fcntl, "F_SEAL_SHRINK", 2)
        | getattr(fcntl, "F_SEAL_GROW", 4) | getattr(fcntl, "F_SEAL_WRITE", 8)
    )
    return (
        getattr(fcntl, "F_ADD_SEALS", 1033),
        getattr(fcntl, "F_GET_SEALS", 1034),
        required,
    )


def linux_memfd_create(name, flags):
    if not sys.platform.startswith("linux"):
        raise SetupError("immutable executable snapshots require Linux")
    create = getattr(os, "memfd_create", None)
    if callable(create):
        return create(name, flags)
    library = ctypes.CDLL(None, use_errno=True)
    create = getattr(library, "memfd_create", None)
    if create is None:
        raise SetupError("immutable executable snapshots are unavailable")
    create.argtypes = (ctypes.c_char_p, ctypes.c_uint)
    create.restype = ctypes.c_int
    descriptor = create(name.encode("utf-8"), flags)
    if descriptor < 0:
        error = ctypes.get_errno()
        raise OSError(error, os.strerror(error))
    return descriptor


@dataclass
class BoundTool:
    path: str
    token: tuple
    descriptor: int
    sealed: bool = False
    digest: bytes = None

    @classmethod
    def open(cls, path):
        descriptor = None
        try:
            named = os.lstat(path)
            descriptor = os.open(path, READ_FLAGS)
        except OSError as error:
            raise SetupError("cannot bind executable {}: {}".format(path, error))
        try:
            opened = os.fstat(descriptor)
            if (
                ident(named) != ident(opened)
                or not stat.S_ISREG(opened.st_mode)
                or opened.st_uid not in (0, os.geteuid())
                or not opened.st_mode & 0o111
                or opened.st_size > MAX_TOOL_BYTES
            ):
                raise SetupError("unsafe executable: {}".format(path))
            result = cls(path, ident(opened), descriptor)
            descriptor = None
            return result
        finally:
            if descriptor is not None:
                os.close(descriptor)

    def verify(self):
        if self.descriptor < 0:
            raise SetupError("executable binding is closed: {}".format(self.path))
        if self.sealed:
            opened = os.fstat(self.descriptor)
            stable = (
                opened.st_dev,
                opened.st_ino,
                opened.st_mode,
                opened.st_uid,
                opened.st_gid,
                opened.st_nlink,
                opened.st_size,
            )
            expected = (
                self.token[0],
                self.token[1],
                self.token[2],
                self.token[3],
                self.token[4],
                self.token[5],
                self.token[6],
            )
            _add_seals, get_seals, required_seals = linux_seal_constants()
            try:
                seals = fcntl.fcntl(self.descriptor, get_seals)
            except (AttributeError, OSError) as error:
                raise SetupError(
                    "cannot verify sealed executable {}: {}".format(self.path, error)
                ) from error
            if (
                stable != expected
                or seals & required_seals != required_seals
                or hashlib.sha256(os.pread(self.descriptor, opened.st_size, 0)).digest()
                != self.digest
            ):
                raise SetupError(
                    "sealed executable changed after binding: {}".format(self.path)
                )
            return
        try:
            named = os.lstat(self.path)
            opened = os.fstat(self.descriptor)
        except OSError as error:
            raise SetupError(
                "cannot verify executable {}: {}".format(self.path, error)
            ) from error
        if ident(named) != self.token or ident(opened) != self.token:
            raise SetupError("executable changed after binding: {}".format(self.path))

    def read_prefix(self, limit=4096):
        if self.descriptor < 0:
            raise SetupError("executable binding is closed: {}".format(self.path))
        return os.pread(self.descriptor, limit, 0)

    def trusted_system_route(self):
        if self.sealed:
            return False
        if (
            os.geteuid() == 0
            or self.token[3] != 0
            or stat.S_IMODE(self.token[2]) & 0o022
            or os.path.realpath(self.path) != os.path.abspath(self.path)
            or os.access(self.path, os.W_OK)
        ):
            return False
        current = os.path.dirname(self.path)
        while True:
            try:
                item = os.lstat(current)
            except OSError:
                return False
            if (
                not stat.S_ISDIR(item.st_mode)
                or item.st_uid != 0
                or stat.S_IMODE(item.st_mode) & 0o022
                or os.access(current, os.W_OK)
            ):
                return False
            parent = os.path.dirname(current)
            if parent == current:
                return True
            current = parent

    @classmethod
    def sealed_bytes(cls, path, data, executable=True):
        add_seals, get_seals, required_seals = linux_seal_constants()
        flags = getattr(os, "MFD_CLOEXEC", 0x0001) | getattr(
            os, "MFD_ALLOW_SEALING", 0x0002
        )
        descriptor = linux_memfd_create("odysseus-runtime", flags)
        try:
            write_all(descriptor, data)
            os.fsync(descriptor)
            os.fchmod(descriptor, 0o500 if executable else 0o400)
            fcntl.fcntl(descriptor, add_seals, required_seals)
            opened = os.fstat(descriptor)
            if (
                not stat.S_ISREG(opened.st_mode)
                or opened.st_uid != os.geteuid()
                or opened.st_nlink != 0
                or stat.S_IMODE(opened.st_mode) != (0o500 if executable else 0o400)
                or opened.st_size != len(data)
                or fcntl.fcntl(descriptor, get_seals) & required_seals != required_seals
            ):
                raise SetupError("unsafe sealed executable snapshot")
            return cls(
                path,
                ident(opened),
                descriptor,
                sealed=True,
                digest=hashlib.sha256(data).digest(),
            )
        except BaseException:
            os.close(descriptor)
            raise

    def snapshot(self, tree, name):
        if (
            not name
            or name in (".", "..")
            or os.sep in name
            or (os.altsep is not None and os.altsep in name)
        ):
            raise SetupError("invalid executable snapshot name")
        tree.verify()
        self.verify()
        data = read_fd(self.descriptor, MAX_TOOL_BYTES)
        if len(data) != self.token[6]:
            raise SetupError("executable changed while snapshotting")
        result = self.sealed_bytes(os.path.join(tree.path, name), data)
        self.verify()
        tree.verify()
        result.verify()
        return result

    def close(self):
        descriptor = self.descriptor
        if descriptor < 0:
            return
        self.descriptor = -1
        os.close(descriptor)


