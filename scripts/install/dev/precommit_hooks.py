def _single_metadata_path(data, label):
    try:
        value = data.decode("utf-8", "strict")
    except UnicodeError as error:
        raise SetupError("{} is not UTF-8".format(label)) from error
    if not value or "\x00" in value or "\n" in value or "\r" in value:
        raise SetupError("{} must contain one path".format(label))
    return value


def _bind_repository_metadata(directory, path):
    """Bind Git metadata from filesystem objects, independent of Git output."""

    git_entry = os.stat(".git", dir_fd=directory.descriptor, follow_symlinks=False)
    opened = []
    try:
        if stat.S_ISDIR(git_entry.st_mode):
            git_path = os.path.join(path, ".git")
            git_dir = BoundDir.open_at(
                directory.descriptor, ".git", git_path, safe=True
            )
        elif stat.S_ISREG(git_entry.st_mode):
            pointer = BoundFile.open(".git", directory_fd=directory.descriptor)
            line = _single_metadata_path(pointer.data.rstrip(b"\n"), ".git file")
            prefix = "gitdir: "
            if not line.startswith(prefix) or not line[len(prefix) :]:
                raise SetupError(".git file has an invalid gitdir record")
            raw = line[len(prefix) :]
            git_path = os.path.abspath(
                raw if os.path.isabs(raw) else os.path.join(path, raw)
            )
            git_dir = BoundDir.open(git_path, safe=True)
        else:
            raise SetupError(".git is not a direct directory or gitfile")
        opened.append(git_dir)

        try:
            common_file = BoundFile.open("commondir", directory_fd=git_dir.descriptor)
        except SetupError as error:
            cause = error.__cause__
            if not isinstance(cause, FileNotFoundError) and "No such file" not in str(
                error
            ):
                raise
            common_path = git_dir.path
        else:
            raw = _single_metadata_path(common_file.data.rstrip(b"\n"), "Git commondir")
            common_path = os.path.abspath(
                raw if os.path.isabs(raw) else os.path.join(git_dir.path, raw)
            )
        common = BoundDir.open(common_path, safe=True)
        opened.append(common)
        return git_dir, common
    except BaseException:
        for value in reversed(opened):
            value.close()
        raise


