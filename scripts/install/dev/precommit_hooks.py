def read_fd(descriptor, limit=4 * 1024 * 1024):
    os.lseek(descriptor, 0, os.SEEK_SET)
    result = bytearray()
    while True:
        chunk = os.read(descriptor, min(65536, limit + 1 - len(result)))
        if not chunk:
            return bytes(result)
        result.extend(chunk)
        if len(result) > limit:
            raise SetupError("file exceeds the allowed size")


def write_all(descriptor, data):
    view = memoryview(data)
    while view:
        written = os.write(descriptor, view)
        if written <= 0:
            raise SetupError("write made no progress")
        view = view[written:]


@dataclass
class BoundFile:
    path: str
    token: tuple
    data: bytes
    executable: bool
    directory_fd: int = None

    @classmethod
    def open(cls, path, executable=None, directory_fd=None, limit=MAX_RUNTIME_BYTES):
        try:
            named = os.stat(path, dir_fd=directory_fd, follow_symlinks=False)
            descriptor = os.open(path, READ_FLAGS, dir_fd=directory_fd)
        except OSError as error:
            raise SetupError("cannot bind {}: {}".format(path, error))
        try:
            opened = os.fstat(descriptor)
            if ident(named) != ident(opened) or not stat.S_ISREG(opened.st_mode):
                raise SetupError("{} is not a direct regular file".format(path))
            if (
                opened.st_uid not in (0, os.geteuid())
                or (opened.st_uid == os.geteuid() and opened.st_nlink != 1)
                or (opened.st_uid == 0 and stat.S_IMODE(opened.st_mode) & 0o022)
            ):
                raise SetupError("{} has an unsafe owner or link count".format(path))
            data = read_fd(descriptor, limit)
            after = os.fstat(descriptor)
            named_after = os.stat(path, dir_fd=directory_fd, follow_symlinks=False)
            if ident(opened) != ident(after) or ident(after) != ident(named_after):
                raise SetupError("{} changed while reading".format(path))
            is_executable = bool(after.st_mode & 0o111)
            if executable is not None and executable != is_executable:
                raise SetupError("{} has an invalid executable mode".format(path))
            return cls(path, ident(after), data, is_executable, directory_fd)
        finally:
            os.close(descriptor)

    def verify(self):
        current = BoundFile.open(self.path, directory_fd=self.directory_fd)
        if current.token != self.token or current.data != self.data:
            raise SetupError("{} changed after binding".format(self.path))


